# ================================================================ 内容 DSL
def h1(t):
    return ('h1', t)


def h2(t):
    return ('h2', t)


def h3(t):
    return ('h3', t)


def p(t, bold=False, indent=True, size=12):
    """正文段落（默认首行缩进两字）。"""
    return ('p', t, bold, indent, size)


def pn(t, bold=False, size=12):
    """正文段落（不缩进），用于承接表格或列表的说明句。"""
    return ('pn', t, bold, size)


def b(t):
    """项目符号段落。"""
    return ('b', t)


def tbl(headers, rows, widths=None, caption=None, size=9.5, keep=None):
    """keep=True 强制整表同页；keep=False 允许跨页；None 按估算行数自动判断。"""
    return ('table', headers, rows, widths, caption, size, keep)


def code(t, size=10):
    return ('code', t, size)


def center(t, size=12, bold=False):
    return ('center', t, size, bold)


def qa(tag, q, ans):
    return ('qa', tag, q, ans)


def pb():
    """下一个标题另起一页。"""
    return ('pb',)


def mdnew(path, title):
    """Markdown 渲染时分卷标记；DOCX 渲染时忽略。"""
    return ('mdnew', path, title)


