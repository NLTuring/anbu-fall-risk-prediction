A(h2('5.1 创新点一：面向步态测量任务的姿态估计改进'))
A(h3('第一段：现有做法为什么不够'))
A(p('现有姿态估计模型的评价体系是为“通用人体姿态理解”建立的：'
    '指标是关键点平均精度（AP），协议是通用人体关键点集，'
    '应用场景是单帧图像上的人体姿态识别。'
    '把这套模型直接搬到步态测量上，会出现三处系统性的不匹配。'))
A(b('**协议不匹配。**通用关键点集对下肢的标注粒度不足以支撑步态计算：'
    '足跟、足尖、骨盆中点这些对步态周期分割至关重要的点缺失，'
    '导致“足何时触地”这个步态分析的起点只能靠踝点近似推断，'
    '误差会沿着整个计算链路传播。'))
